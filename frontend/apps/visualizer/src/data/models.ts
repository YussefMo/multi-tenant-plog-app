export interface ErdEdge {
  id: string;
  source: string;
  target: string;
  label: string;
}

export const erdEdges: ErdEdge[] = models.flatMap((model) =>
  model.relations.map((relation) => ({
    id: `${model.name}-${relation.model}-${relation.foreignKey}`,
    source: model.name,
    target: relation.model,
    label: `${relation.type} ${relation.foreignKey}`,
  })),
);
