<?php

namespace App\Http\Controllers\Api;

use App\Http\Controllers\Controller;
use App\Services\StripeWebhookService;
use Dedoc\Scramble\Attributes\BodyParameter;
use Dedoc\Scramble\Attributes\Endpoint;
use Dedoc\Scramble\Attributes\HeaderParameter;
use Dedoc\Scramble\Attributes\Response as DocsResponse;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Stripe\Exception\SignatureVerificationException;
use Stripe\Webhook;
use UnexpectedValueException;

class StripeWebhookController extends Controller
{
  #[Endpoint(
    title: 'Stripe webhook',
    description: 'Receive and verify Stripe events. Signature verification is mandatory and events are idempotent.',
  )]
  #[HeaderParameter('Stripe-Signature', 'Signature generated by Stripe for the raw payload.', required: true, example: 't=123,v1=...')]
  #[BodyParameter('id', 'Stripe event ID.', required: true, type: 'string', example: 'evt_123')]
  #[BodyParameter('type', 'Stripe event type.', required: true, type: 'string', example: 'customer.subscription.updated')]
  #[BodyParameter('data', 'Stripe event data object.', required: true, type: 'object', example: ['object' => ['id' => 'sub_123']])]
  #[DocsResponse(status: 200, description: 'Event accepted or already processed.', type: 'array{received: bool, duplicate?: bool, processed?: bool}')]
  #[DocsResponse(status: 400, description: 'Invalid or missing Stripe signature.', type: 'array{message: string, status: int}')]
  public function __invoke(Request $request, StripeWebhookService $webhooks): JsonResponse
  {
    $payload = $request->getContent();
    $signature = (string) $request->header('Stripe-Signature');

    try {
      $event = Webhook::constructEvent(
        $payload,
        $signature,
        (string) config('services.stripe.webhook_secret'),
      );
    } catch (UnexpectedValueException|SignatureVerificationException) {
      abort(400, 'Invalid Stripe webhook signature.');
    }

    $result = $webhooks->handle($event->toArray());

    return response()->json([
      'received' => true,
      ...$result,
    ]);
  }
}
