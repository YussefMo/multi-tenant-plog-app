<?php

namespace App\Providers;

use Dedoc\Scramble\Scramble;
use Dedoc\Scramble\Support\Generator\OpenApi;
use Dedoc\Scramble\Support\Generator\Operation;
use Dedoc\Scramble\Support\Generator\SecurityRequirement;
use Dedoc\Scramble\Support\Generator\SecurityScheme;
use Illuminate\Support\ServiceProvider;

class ScrambleServiceProvider extends ServiceProvider
{
  public function boot(): void
  {
    Scramble::afterOpenApiGenerated(function (OpenApi $openApi): void {
      $openApi->components->addSecurityScheme(
        'tenantSession',
        SecurityScheme::apiKey('cookie', 'tenant_session')
          ->setDescription('Tenant session cookie. Get a CSRF token, then call POST /api/v1/auth/login.'),
      );
      $openApi->components->addSecurityScheme(
        'ownerSession',
        SecurityScheme::apiKey('cookie', 'owner_session')
          ->setDescription('Owner session cookie. Get an owner CSRF token, then call POST /api/v1/owner/auth/login.'),
      );
      $openApi->components->addSecurityScheme(
        'csrfToken',
        SecurityScheme::apiKey('header', 'X-CSRF-TOKEN')
          ->setDescription('CSRF token from GET /api/v1/csrf-token or GET /api/v1/owner/csrf-token.'),
      );
      $openApi->components->addSecurityScheme(
        'stripeSignature',
        SecurityScheme::apiKey('header', 'Stripe-Signature')
          ->setDescription('Signature generated by Stripe for the webhook payload.'),
      );

      foreach ($openApi->paths as $path) {
        foreach ($path->operations as $operation) {
          $this->applySecurity($path->path, $operation);
        }
      }
    });
  }

  private function applySecurity(string $path, Operation $operation): void
  {
    $path = '/'.ltrim($path, '/');

    if (str_starts_with($path, '/api/')) {
      $path = substr($path, 4);
    }

    $method = strtolower($operation->method);

    if ($path === '/v1/stripe/webhook') {
      $operation->addSecurity(new SecurityRequirement(['stripeSignature' => []]));

      return;
    }

    $publicPaths = [
      '/v1/csrf-token',
      '/v1/owner/csrf-token',
      '/v1/health',
      '/v1/auth/login',
      '/v1/auth/register',
      '/v1/auth/accept-invitation',
      '/v1/auth/support-login',
      '/v1/owner/auth/login',
      '/v1/billing/checkout/success',
      '/v1/billing/checkout/cancel',
      '/v1/billing/portal/return',
    ];

    if (in_array($path, $publicPaths, true)) {
      if ($this->requiresCsrf($method)) {
        $operation->addSecurity(new SecurityRequirement(['csrfToken' => []]));
      }

      return;
    }

    $requirements = str_starts_with($path, '/v1/owner')
      ? ['ownerSession' => []]
      : ['tenantSession' => []];

    if ($this->requiresCsrf($method)) {
      $requirements['csrfToken'] = [];
    }

    $operation->addSecurity(new SecurityRequirement($requirements));
  }

  private function requiresCsrf(string $method): bool
  {
    return in_array($method, ['post', 'put', 'patch', 'delete'], true);
  }
}
